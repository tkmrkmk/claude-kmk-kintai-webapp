/** マスタ未収録の年度でも最低限外さないための年末年始フォールバック */
function yearEndFallback(key: string): string | undefined {
  const md = key.slice(5);
  if (md === '12-29' || md === '12-30' || md === '12-31') return '年末休';
  if (md === '01-01' || md === '01-02' || md === '01-03') return '年始休';
  return undefined;
}

export function holidayName(key: string): string | undefined {
  return HOLIDAYS[key] ?? yearEndFallback(key);
}

export function isHoliday(key: string): boolean {
  return holidayName(key) !== undefined;
}
